#!/usr/bin/env node
// Fork-only: copies the Morax design kit's web tokens into the agent grid, scoped to
// `.morax-grid` and bound to Emdash's theme classes (`.emlight` / `.emdark`) instead of
// `:root` / `prefers-color-scheme`, so nothing leaks into the rest of the app.
//
// Usage: node tooling/morax-design/sync-grid-tokens.mjs [path/to/morax-design]
// Default kit path: $MORAX_DESIGN_DIR or ~/Documents/Claude/Projects/morax-design
import { readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const kitDir = resolve(
  process.argv[2] ??
    process.env.MORAX_DESIGN_DIR ??
    join(homedir(), 'Documents/Claude/Projects/morax-design')
);
const source = readFileSync(join(kitDir, 'web/tokens.css'), 'utf8');
const version = JSON.parse(readFileSync(join(kitDir, 'tokens.json'), 'utf8')).version;

function block(css, opener) {
  const start = css.indexOf(opener);
  if (start === -1) throw new Error(`Kit tokens.css has no "${opener}" block`);
  let depth = 0;
  for (let i = css.indexOf('{', start); i < css.length; i++) {
    if (css[i] === '{') depth++;
    if (css[i] === '}' && --depth === 0) return css.slice(css.indexOf('{', start) + 1, i);
  }
  throw new Error(`Unterminated "${opener}" block`);
}

// `color-scheme` belongs to the app shell, not to the grid.
const keep = (body) => body.replace(/^[ \t]*color-scheme:[^;]*;\n/m, '');

const light = keep(block(source, ':root {'));
const dark = keep(block(source, ':root[data-theme="dark"] {'));

const output = `/* Generated by tooling/morax-design/sync-grid-tokens.mjs from morax-design tokens v${version}.
 * Do not edit by hand: change the kit, then re-run the script. */
.morax-grid {${light}}

.emdark .morax-grid {${dark}}
`;

const target = join(
  dirname(fileURLToPath(import.meta.url)),
  '../../src/core/features/workbench/browser/task-grid/morax-design-tokens.css'
);
// Match the repo formatter (oxfmt: single quotes in CSS) so the file stays check-clean.
writeFileSync(target, output.replaceAll('"', "'"));
console.log(`Wrote ${target} (tokens v${version})`);
